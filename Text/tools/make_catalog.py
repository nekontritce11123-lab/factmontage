def main(argv=None):
    global CHECK
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    CHECK = parser.parse_args(argv).check
    from life_catalog import LIFE
    rows=[]
    for category, recipes in CATALOG.items():
        for r in recipes:
            name,k,e,d,a,rot,m,g,o,desc=r
            rows.append(dict(id=len(rows)+1,name=name,category=category,kernel=k,ease=e,direction=d,amplitude=a,rotation=rot,mask=m,group=g,order=o,description=desc,cost='средняя' if k in (4,42,45,46) else 'низкая'))
    for row, life in zip(rows,LIFE):
        row['life']=life
    assert len(rows)==100
    assert len({r['name'] for r in rows})==100
    emit(ROOT/'web/catalog.json', json.dumps(rows,ensure_ascii=False,indent=2)+'\n')
    header='// Generated by tools/make_catalog.py. Do not edit.\nstatic const Recipe RECIPES[101] = {\n  {0,0,0,0,0,0,0},\n'
    for r in rows:
        header+='  {%d,%d,%.8ff,%.8ff,%.8ff,%d,%d}, // %d %s\n'%(r['kernel'],r['ease'],r['direction'],r['amplitude'],r['rotation'],r['mask'],r['order'],r['id'],r['name'])
    header+='};\n'
    emit(ROOT/'src/recipes.inc', header)
    lines=['# Каталог 100 анимаций','', 'Это 100 авторских рецептов на 48 механиках (не 100 независимых движков). Направление, группировка, порядок, кривая и маска входят в рецепт. Все рецепты доступны для входа, выхода и второго слоя движения.','']
    for category in CATALOG:
        lines+=['## '+category,'']
        for r in rows:
            if r['category']==category: lines += [f"**{r['id']:03}. {r['name']}** — {r['description']}",'']
    emit(ROOT/'docs/CATALOG_RU.md', '\n'.join(lines))
    print('Generated',len(rows),'presets;',len({r['kernel'] for r in rows}),'used kernels')

    life_header='// Generated by tools/make_catalog.py. One authored hold profile per preset.\nstatic const LifeRecipe LIFE_RECIPES[101] = {\n  {3,7.f,.25f,0.f,.1f},\n'
    for row in rows:
        r=row['life']
        life_header+='  {%d,%.8ff,%.8ff,%.8ff,%.8ff}, // %03d %s\n'%(r['kind'],r['period'],r['amount'],r['spread'],r['drift'],row['id'],r['name'])
    life_header+='};\n'
    emit(ROOT/'src/life_recipes.inc', life_header)
    lines=['# 100 профилей жизни текста · v0.2', '', 'Для каждого перехода задано отдельное продолжение. Это 100 настроенных рецептов на 25 используемых механиках; не 100 независимых алгоритмов. Сила и темп регулируются отдельно от входа/выхода. Все движения вычисляются от исходной вёрстки, а не накапливаются по кадрам.', '']
    for r in rows:
        l=r['life']
        lines.extend([f"**{r['id']:03}. {r['name']} → {l['name']}**", l['description']+f" Базовый цикл: {l['period']:g} с.", ''])
    emit(ROOT/'docs/LIFE_CATALOG_RU.md', '\n'.join(lines))

if __name__ == '__main__':
    main()
